import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { chromium } from "playwright";

const baseURL = process.env.DEMO_BASE_URL;
if (!baseURL) throw new Error("Set DEMO_BASE_URL to the deployed app you are recording.");

const outDir = resolve("demos/live-application/v1/recording");
await mkdir(outDir, { recursive: true });
const voiceInput = process.env.DEMO_VOICE_INPUT ? resolve(process.env.DEMO_VOICE_INPUT) : null;
const args = voiceInput
  ? ["--use-fake-ui-for-media-stream", "--use-fake-device-for-media-stream", `--use-file-for-fake-audio-capture=${voiceInput}`]
  : [];
const browser = await chromium.launch({ headless: process.env.DEMO_HEADLESS === "true", args });
const context = await browser.newContext({
  viewport: { width: 1920, height: 1080 },
  deviceScaleFactor: 1,
  permissions: ["microphone"],
  recordVideo: { dir: outDir, size: { width: 1920, height: 1080 } },
});
await context.addInitScript(() => {
  document.addEventListener("DOMContentLoaded", () => {
    if (document.documentElement) document.documentElement.style.zoom = "1.12";
  }, { once: true });
});
const page = await context.newPage();
const marks = [];
const errors = [];
let captureFailure = null;
page.on("pageerror", (error) => errors.push(error.message));
page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });

async function mark(label, dwellMs = 8000) {
  marks.push({ atSeconds: Math.round((Date.now() - started) / 100) / 10, label, url: page.url() });
  await page.waitForTimeout(dwellMs);
}

const started = Date.now();
try {
  // The deployed app keeps realtime/polling connections active, so networkidle
  // is not a meaningful readiness signal. Each scene waits for its real UI.
  await page.goto(baseURL, { waitUntil: "domcontentloaded", timeout: 60_000 });
  await page.getByRole("heading", { name: /A place to think things through/i }).waitFor({ state: "visible", timeout: 30_000 });
  await mark("Problem, product promise, and choice principles", 15_000);

  await page.getByRole("link", { name: "Start a conversation" }).click();
  await page.getByRole("button", { name: "Continue with demo account" }).waitFor({ state: "visible", timeout: 30_000 });
  await mark("Email/password entry and shared demo option", 12_000);
  await page.getByRole("button", { name: "Continue with demo account" }).click();
  await page.waitForURL(/\/connect\/member(?:\?.*)?$/, { timeout: 30_000 });
  await page.getByPlaceholder("Share what is happening, in your own words…").waitFor({ state: "visible", timeout: 30_000 });
  await mark("Authenticated live member workspace", 8_000);

  await page.getByPlaceholder("Share what is happening, in your own words…").fill(
    "I am under pressure to make a decision for my family before I feel ready. I want to be honest, but also ask for time to think. What is one small way I could start that conversation?",
  );
  await page.getByRole("button", { name: "Send", exact: true }).click();
  const answer = page.locator(".cx-msg-adviser").last();
  await answer.waitFor({ state: "visible", timeout: 90_000 });
  await answer.getByText(/Generated by Meta Muse (Wonder|Spark)/).waitFor({ state: "visible", timeout: 5_000 });
  await mark("Live Meta advice and actual serving-model attribution", 30_000);
  const reveal = page.getByRole("button", { name: /show relevant communities/i });
  if (await reveal.count()) {
    await reveal.click();
    await page.getByText("Communities that may understand", { exact: true }).waitFor({ state: "visible", timeout: 30_000 });
    await mark("Member-controlled reveal of live community matches", 22_000);
  }

  await page.goto(new URL("/communities", baseURL).toString(), { waitUntil: "domcontentloaded", timeout: 60_000 });
  await page.getByRole("heading", { name: "Communities", exact: true }).waitFor({ state: "visible", timeout: 30_000 });
  await page.getByText("Finding steady ground", { exact: true }).waitFor({ state: "visible", timeout: 30_000 });
  await mark("Supabase community directory and live activity counts", 25_000);

  await page.goto(new URL("/communities/propose", baseURL).toString(), { waitUntil: "domcontentloaded", timeout: 60_000 });
  await page.getByLabel("Community name").fill("Coordinating family caregiving");
  await page.getByLabel("What would people come together around?").fill(
    "Adults sharing practical ways to coordinate support for an aging parent across siblings and different cities. This is for routines and communication, not medical or legal advice.",
  );
  await page.getByLabel(/Topics/).fill("family communication, caregiving routines, shared responsibilities");
  await page.getByRole("button", { name: "Draft with Meta" }).click();
  await page.getByText(/Meta Muse (Wonder|Spark) · editable draft/).waitFor({ state: "visible", timeout: 90_000 });
  await page.getByText("Community scope suggestions", { exact: true }).scrollIntoViewIfNeeded();
  await mark("Live Meta community setup copilot and editable private draft", 40_000);
  await page.mouse.wheel(0, 420);
  await page.waitForTimeout(4_000);

  await page.goto(new URL("/app", baseURL).toString(), { waitUntil: "domcontentloaded", timeout: 60_000 });
  const voiceButton = page.getByRole("button", { name: "Record a voice message" });
  await voiceButton.waitFor({ state: "visible", timeout: 30_000 });
  await mark("Private Meta chat with visible Meta voice transcription", 12_000);
  if (voiceInput) {
    await voiceButton.click();
    await page.getByRole("button", { name: "Stop voice recording" }).waitFor({ state: "visible", timeout: 10_000 });
    await page.waitForTimeout(7_500);
    await page.getByRole("button", { name: "Stop voice recording" }).click();
    await page.getByRole("button", { name: "Record a voice message" }).waitFor({ state: "visible", timeout: 60_000 });
    await page.waitForFunction(() => document.querySelector("#private-message")?.value.trim().length > 0, null, { timeout: 60_000 });
    const transcript = await page.locator("#private-message").inputValue();
    const repeatedStart = (transcript.match(/\bi feel\b/gi) ?? []).length > 1;
    if (!/decide for my family/i.test(transcript) || !/need more time/i.test(transcript) || repeatedStart) {
      throw new Error(`Meta Voice Transcribe returned an incomplete or repeated transcript: ${transcript}`);
    }
    await mark("Meta Voice Transcribe result shown as editable text; intentionally unsent", 22_000);
  } else {
    console.warn("DEMO_VOICE_INPUT is unset; this take will show the voice control but will not submit a recording.");
  }

  const assignmentsResponsePromise = page.waitForResponse((response) => new URL(response.url()).pathname === "/api/moderation/assignments", { timeout: 30_000 });
  await page.goto(new URL("/moderation", baseURL).toString(), { waitUntil: "domcontentloaded", timeout: 60_000 });
  await page.getByRole("heading", { name: "Moderation review" }).waitFor({ state: "visible", timeout: 30_000 });
  const assignmentsResponse = await assignmentsResponsePromise;
  const assignmentsBody = await assignmentsResponse.json().catch(() => null);
  if (assignmentsResponse.status() !== 200 || !Array.isArray(assignmentsBody?.assignments) || assignmentsBody.assignments.length !== 0) {
    throw new Error("The live demo account did not return the expected read-only empty reviewer state.");
  }
  await page.getByRole("heading", { name: "No reviewer access" }).waitFor({ state: "visible", timeout: 10_000 });
  await mark("Human review boundary and actual reviewer authorization state", 18_000);

  await page.goto(baseURL, { waitUntil: "domcontentloaded", timeout: 60_000 });
  await mark("Impact close: private reflection, choice, and peer connection", 20_000);
  await page.waitForTimeout(2200);
  if (errors.length) console.warn(`Browser reported ${errors.length} console/page errors; inspect before publishing.`);
} catch (error) {
  captureFailure = error;
  console.error(`Capture stopped: a required live feature did not appear. No fallback UI was injected. ${error instanceof Error ? error.message : String(error)}`);
} finally {
  const video = page.video();
  await context.close();
  if (video) {
    const target = resolve(outDir, "harmonise-live-v1.webm");
    await video.saveAs(target);
    const manifest = { video: target, baseURL, marks, errors, durationSeconds: Math.round((Date.now() - started) / 100) / 10 };
    await writeFile(resolve(outDir, "capture-manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
    console.log(JSON.stringify(manifest, null, 2));
  }
  await browser.close();
}

if (captureFailure) throw captureFailure;
