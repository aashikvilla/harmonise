import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { chromium } from "playwright";

const baseURL = process.env.DEMO_BASE_URL;
if (!baseURL) throw new Error("Set DEMO_BASE_URL to the deployed app you are recording.");

const outDir = resolve("demos/live-application/v2/recording");
await mkdir(outDir, { recursive: true });
const voiceInput = process.env.DEMO_VOICE_INPUT ? resolve(process.env.DEMO_VOICE_INPUT) : null;
const args = voiceInput
  ? ["--use-fake-ui-for-media-stream", "--use-fake-device-for-media-stream", `--use-file-for-fake-audio-capture=${voiceInput}`]
  : [];
const browser = await chromium.launch({ headless: process.env.DEMO_HEADLESS === "true", args });
const context = await browser.newContext({
  viewport: { width: 1920, height: 1080 },
  deviceScaleFactor: 1,
  permissions: ["microphone"],
  recordVideo: { dir: outDir, size: { width: 1920, height: 1080 } },
});
const page = await context.newPage();
const marks = [];
const errors = [];
let captureFailure = null;
page.on("pageerror", (error) => errors.push(error.message));
page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });

const started = Date.now();
async function mark(label, dwellMs = 5000) {
  marks.push({ atSeconds: Math.round((Date.now() - started) / 100) / 10, label, url: page.url() });
  await page.waitForTimeout(dwellMs);
}

async function scrollTo(selector, label, dwellMs) {
  await page.evaluate((target) => document.querySelector(target)?.scrollIntoView({ behavior: "smooth", block: "start" }), selector);
  await page.waitForTimeout(1400);
  await mark(label, dwellMs);
}

try {
  await page.goto(baseURL, { waitUntil: "domcontentloaded", timeout: 45_000 });
  await page.getByRole("heading", { name: /You don't need the right words to begin/i }).waitFor({ state: "visible", timeout: 20_000 });
  await mark("Animated homepage: Harmonise loop mark, window illustration, and the first-step promise", 8000);
  await scrollTo("#why-harmonise", "Homepage: why a private first step", 4000);
  await scrollTo("#how-it-works", "Homepage: separate reflection, discovery, and sharing", 4000);
  await scrollTo("#ai-with-boundaries", "Homepage: actual Meta model roles and boundaries", 4000);

  await page.getByRole("link", { name: "See how it feels", exact: true }).click();
  await page.getByRole("button", { name: "Continue with demo account" }).waitFor({ state: "visible", timeout: 20_000 });
  await mark("Sign in with the shared demo account", 3500);
  await page.getByRole("button", { name: "Continue with demo account" }).click();
  await page.waitForURL(/\/connect\/member(?:\?.*)?$/, { timeout: 25_000 });
  const prompt = page.getByPlaceholder("Share what is happening, in your own words…");
  await prompt.waitFor({ state: "visible", timeout: 20_000 });
  await prompt.fill("I feel pressured to decide for my family before I am ready. I want to be honest and ask for time. What is one small way to start?");
  await page.getByRole("button", { name: "Send", exact: true }).click();
  const answer = page.locator(".cx-msg-adviser").last();
  await answer.waitFor({ state: "visible", timeout: 75_000 });
  await answer.getByText(/Generated by Meta Muse (Wonder|Spark)/).waitFor({ state: "visible", timeout: 5_000 });
  await mark("Live Meta advice, practical steps, and actual model attribution", 6500);

  const reveal = page.getByRole("button", { name: /show relevant communities/i });
  if (await reveal.count()) {
    await reveal.click();
    await page.getByText("Communities that may understand", { exact: true }).waitFor({ state: "visible", timeout: 20_000 });
    await mark("Member chooses to reveal real community matches", 4500);
  }

  await page.goto(new URL("/communities", baseURL).toString(), { waitUntil: "domcontentloaded", timeout: 45_000 });
  await page.getByRole("heading", { name: "Communities", exact: true }).waitFor({ state: "visible", timeout: 20_000 });
  await page.getByText("Finding steady ground", { exact: true }).waitFor({ state: "visible", timeout: 20_000 });
  await mark("Live Supabase directory and aggregate community activity", 5000);

  await page.goto(new URL("/communities/propose", baseURL).toString(), { waitUntil: "domcontentloaded", timeout: 45_000 });
  await page.getByLabel("Community name").fill("Coordinating family caregiving");
  await page.getByLabel("What would people come together around?").fill(
    "Adults sharing practical ways to coordinate support for an aging parent across siblings and different cities. This is for routines and communication, not medical or legal advice.",
  );
  await page.getByLabel(/Topics/).fill("family communication, caregiving routines, shared responsibilities");
  await page.getByRole("button", { name: "Draft with Meta" }).click();
  await page.getByText(/Meta Muse (Wonder|Spark) · editable draft/).waitFor({ state: "visible", timeout: 75_000 });
  await page.getByText("Community scope suggestions", { exact: true }).scrollIntoViewIfNeeded();
  await mark("Live Meta-assisted scope draft; editable and not submitted", 7000);
  await page.mouse.wheel(0, 360);
  await page.waitForTimeout(2500);

  await page.goto(new URL("/app", baseURL).toString(), { waitUntil: "domcontentloaded", timeout: 45_000 });
  const voiceButton = page.getByRole("button", { name: "Record a voice message" });
  await voiceButton.waitFor({ state: "visible", timeout: 25_000 });
  await mark("Private chat: Meta voice transcription control", 2000);
  if (!voiceInput) throw new Error("Set DEMO_VOICE_INPUT to demonstrate real Meta Voice Transcribe.");
  await voiceButton.click();
  await page.getByRole("button", { name: "Stop voice recording" }).waitFor({ state: "visible", timeout: 10_000 });
  await page.waitForTimeout(7500);
  await page.getByRole("button", { name: "Stop voice recording" }).click();
  await page.getByRole("button", { name: "Record a voice message" }).waitFor({ state: "visible", timeout: 60_000 });
  await page.waitForFunction(() => document.querySelector("#private-message")?.value.trim().length > 0, null, { timeout: 60_000 });
  const transcript = await page.locator("#private-message").inputValue();
  const repeatedStart = (transcript.match(/\bi feel\b/gi) ?? []).length > 1;
  if (!/decide for my family/i.test(transcript) || !/need more time/i.test(transcript) || repeatedStart) {
    throw new Error(`Meta Voice Transcribe returned an incomplete or repeated transcript: ${transcript}`);
  }
  await mark("Meta Voice Transcribe: complete editable draft, intentionally unsent", 5000);

  await page.goto(baseURL, { waitUntil: "domcontentloaded", timeout: 45_000 });
  await page.getByRole("heading", { name: /You don't need the right words to begin/i }).waitFor({ state: "visible", timeout: 20_000 });
  await scrollTo("#the-intent", "Close: intended impact and first-step invitation", 9000);
  if (errors.length) console.warn(`Browser reported ${errors.length} console/page errors; review capture-manifest.json.`);
} catch (error) {
  captureFailure = error;
  console.error(`Capture stopped: ${error instanceof Error ? error.message : String(error)}`);
} finally {
  const video = page.video();
  await context.close();
  if (video) {
    const target = resolve(outDir, "harmonise-live-v2.webm");
    await video.saveAs(target);
    const manifest = { video: target, baseURL, marks, errors, captureElapsedSeconds: Math.round((Date.now() - started) / 100) / 10 };
    await writeFile(resolve(outDir, "capture-manifest-v2.json"), `${JSON.stringify(manifest, null, 2)}\n`);
    console.log(JSON.stringify(manifest, null, 2));
  }
  await browser.close();
}

if (captureFailure) throw captureFailure;
