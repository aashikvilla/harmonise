import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { chromium } from "playwright";

const baseURL = process.env.DEMO_BASE_URL;
if (!baseURL) throw new Error("Set DEMO_BASE_URL to the deployed app you are recording.");

const outDir = resolve("demos/live-application/v2/recording");
await mkdir(outDir, { recursive: true });
const voiceInput = process.env.DEMO_VOICE_INPUT ? resolve(process.env.DEMO_VOICE_INPUT) : null;
if (!voiceInput) throw new Error("Set DEMO_VOICE_INPUT to demonstrate real Meta Voice Transcribe.");
const args = ["--use-fake-ui-for-media-stream", "--use-fake-device-for-media-stream", `--use-file-for-fake-audio-capture=${voiceInput}`];
const browser = await chromium.launch({ headless: process.env.DEMO_HEADLESS === "true", args });
const context = await browser.newContext({
  viewport: { width: 1920, height: 1080 },
  deviceScaleFactor: 1,
  permissions: ["microphone"],
  recordVideo: { dir: outDir, size: { width: 1920, height: 1080 } },
});
const page = await context.newPage();
const marks = [];
const errors = [];
const expectedResponses = [];
const modelAttributions = [];
let savedPrivateConversation = false;
let captureFailure = null;
let signedIn = false;
const started = Date.now();

function elapsedSeconds() {
  return Math.round((Date.now() - started) / 100) / 10;
}

function pathOf(response) {
  try { return new URL(response.url()).pathname; } catch { return response.url(); }
}

page.on("pageerror", (error) => errors.push(error.message));
page.on("console", (message) => {
  if (message.type() === "error" && !/status of 401/i.test(message.text())) errors.push(message.text());
});
page.on("response", (response) => {
  if (response.status() < 400) return;
  const path = pathOf(response);
  if (response.status() === 401 && path === "/api/auth/me" && !signedIn) {
    expectedResponses.push({ status: 401, path, reason: "signed-out account check before demo sign-in" });
    return;
  }
  errors.push(`HTTP ${response.status()} ${path}`);
});

async function mark(label) {
  marks.push({ atSeconds: elapsedSeconds(), label, url: page.url() });
}

async function holdUntil(seconds, label) {
  await mark(label);
  const remaining = seconds * 1000 - (Date.now() - started);
  if (remaining < 0) throw new Error(`The ${label} scene missed its ${seconds}s slot by ${Math.ceil(-remaining / 1000)}s.`);
  await page.waitForTimeout(remaining);
}

async function smoothScroll(selector) {
  await page.evaluate((target) => document.querySelector(target)?.scrollIntoView({ behavior: "smooth", block: "start" }), selector);
  await page.waitForTimeout(1200);
}

async function sendAdvice(prompt, index, timeoutMs = 19_000) {
  const input = page.getByPlaceholder("Share what is happening, in your own words…");
  await input.fill(prompt);
  const responsePromise = page.waitForResponse((response) => pathOf(response) === "/api/advice" && response.request().method() === "POST", { timeout: timeoutMs });
  await page.getByRole("button", { name: "Send", exact: true }).click();
  const response = await responsePromise;
  if (!response.ok()) throw new Error(`Live adviser request ${index} returned HTTP ${response.status()}.`);
  const answer = page.locator(".cx-msg-adviser").nth(index - 1);
  await answer.waitFor({ state: "visible", timeout: timeoutMs });
  const attribution = answer.locator(".cx-ai-note").first();
  await attribution.waitFor({ state: "visible", timeout: 3_000 });
  const actualModelLabel = (await attribution.innerText()).trim();
  if (!/Generated by Meta Muse (Wonder|Spark)/.test(actualModelLabel)) throw new Error(`Advice ${index} had no supported Meta model attribution.`);
  modelAttributions.push({ feature: `adviser-${index}`, label: actualModelLabel });
}

try {
  await page.goto(baseURL, { waitUntil: "domcontentloaded", timeout: 25_000 });
  await page.getByRole("heading", { name: /You don't need the right words to begin/i }).waitFor({ state: "visible", timeout: 10_000 });
  await page.waitForTimeout(5_500);
  await smoothScroll("#why-harmonise");
  await page.waitForTimeout(2_500);
  await smoothScroll("#how-it-works");
  await page.waitForTimeout(2_500);
  await smoothScroll("#ai-with-boundaries");
  await holdUntil(20, "Original animated homepage and product story");

  await page.getByRole("link", { name: "See how it feels", exact: true }).click();
  await page.getByRole("button", { name: "Continue with demo account" }).waitFor({ state: "visible", timeout: 5_000 });
  await page.getByRole("button", { name: "Continue with demo account" }).click();
  await page.waitForURL(/\/connect\/member(?:\?.*)?$/, { timeout: 8_000 });
  const authResponse = await page.request.get(new URL("/api/auth/me", baseURL).toString());
  if (!authResponse.ok()) throw new Error(`Demo sign-in did not establish a session (HTTP ${authResponse.status()}).`);
  signedIn = true;
  await page.getByPlaceholder("Share what is happening, in your own words…").waitFor({ state: "visible", timeout: 3_000 });
  await holdUntil(30, "Shared demo account signs into the live application");

  await sendAdvice("I feel pressured to decide for my family before I am ready. How can I ask for more time without shutting anyone out?", 1);
  await sendAdvice("My siblings and I share caregiving from different cities. What is one practical question we could ask each other this week?", 2);
  const reveal = page.getByRole("button", { name: /show relevant communities/i }).last();
  if (await reveal.count()) {
    await reveal.click({ timeout: 4_000 });
    await page.getByText("Communities that may understand", { exact: true }).waitFor({ state: "visible", timeout: 5_000 });
  }
  await holdUntil(74, "Two live Meta Adviser turns and member-chosen community matches");

  await page.goto(new URL("/communities", baseURL).toString(), { waitUntil: "domcontentloaded", timeout: 12_000 });
  await page.getByRole("heading", { name: "Communities", exact: true }).waitFor({ state: "visible", timeout: 5_000 });
  await page.getByRole("status").filter({ hasText: "Loading communities" }).waitFor({ state: "hidden", timeout: 8_000 });
  const communityCard = page.locator("ul li").first();
  await communityCard.waitFor({ state: "visible", timeout: 5_000 });
  await communityCard.locator("h2").waitFor({ state: "visible", timeout: 3_000 });
  await holdUntil(83, "Fully loaded Supabase directory with real community names and aggregate activity");

  await page.goto(new URL("/communities/propose", baseURL).toString(), { waitUntil: "domcontentloaded", timeout: 10_000 });
  await page.getByLabel("Community name").fill("Coordinating family caregiving");
  await page.getByLabel("What would people come together around?").fill(
    "Adults sharing practical ways to coordinate support for an aging parent across siblings and different cities. This is for routines and communication, not medical or legal advice.",
  );
  await page.getByLabel(/Topics/).fill("family communication, caregiving routines, shared responsibilities");
  const setupPromise = page.waitForResponse((response) => pathOf(response) === "/api/communities/propose/assist" && response.request().method() === "POST", { timeout: 15_000 });
  await page.getByRole("button", { name: "Draft with Meta" }).click();
  const setupResponse = await setupPromise;
  if (!setupResponse.ok()) throw new Error(`Meta setup draft returned HTTP ${setupResponse.status()}.`);
  const setupLabel = page.getByText(/Meta Muse (Wonder|Spark) · editable draft/);
  await setupLabel.waitFor({ state: "visible", timeout: 3_000 });
  const setupAttribution = (await setupLabel.innerText()).trim();
  modelAttributions.push({ feature: "community-setup", label: setupAttribution });
  await page.getByText("Community scope suggestions", { exact: true }).scrollIntoViewIfNeeded();
  await holdUntil(101, "Live editable Meta Wonder community draft, left private and unsubmitted");

  await page.goto(new URL("/app", baseURL).toString(), { waitUntil: "domcontentloaded", timeout: 10_000 });
  await page.getByLabel("Your message").waitFor({ state: "visible", timeout: 7_000 });
  const message = "I keep changing my mind about what my family needs. Can you help me find a way to ask for one more day?";
  await page.locator("#private-message").fill(message);
  const createSessionPromise = page.waitForResponse((response) => pathOf(response) === "/api/sessions" && response.request().method() === "POST", { timeout: 5_000 });
  const chatPromise = page.waitForResponse((response) => pathOf(response) === "/api/chat" && response.request().method() === "POST", { timeout: 12_000 });
  await page.getByRole("button", { name: "Send to adviser" }).click();
  const createdSession = await createSessionPromise;
  if (!createdSession.ok()) throw new Error(`The live private conversation was not saved (HTTP ${createdSession.status()}).`);
  const chatResponse = await chatPromise;
  if (!chatResponse.ok()) throw new Error(`The live Muse Spark chat returned HTTP ${chatResponse.status()}.`);
  const assistantTurns = page.locator("article").filter({ hasText: "Harmonise · Meta AI" });
  await assistantTurns.first().waitFor({ state: "visible", timeout: 5_000 });
  await page.getByText("Meta Muse Spark", { exact: true }).waitFor({ state: "visible", timeout: 3_000 });
  savedPrivateConversation = true;
  modelAttributions.push({ feature: "saved-private-chat", label: "Meta Muse Spark" });
  await page.getByText("AI reflection · your review", { exact: true }).waitFor({ state: "visible", timeout: 3_000 });
  await holdUntil(117, "Live Muse Spark saved chat and member-reviewable themes");

  const voiceButton = page.getByRole("button", { name: "Record a voice message" });
  await voiceButton.click();
  await page.getByRole("button", { name: "Stop voice recording" }).waitFor({ state: "visible", timeout: 3_000 });
  await page.waitForTimeout(7_500);
  await page.getByRole("button", { name: "Stop voice recording" }).click();
  await page.getByRole("button", { name: "Record a voice message" }).waitFor({ state: "visible", timeout: 15_000 });
  await page.waitForFunction(() => document.querySelector("#private-message")?.value.trim().length > 0, null, { timeout: 3_000 });
  const transcript = await page.locator("#private-message").inputValue();
  const repeatedStart = (transcript.match(/\bi feel\b/gi) ?? []).length > 1;
  if (!/decide for my family/i.test(transcript) || !/need more time/i.test(transcript) || repeatedStart) {
    throw new Error(`Meta Voice Transcribe returned an incomplete or repeated transcript: ${transcript}`);
  }
  await holdUntil(134, "Complete editable Meta Voice Transcribe draft, intentionally unsent");

  await page.goto(baseURL, { waitUntil: "domcontentloaded", timeout: 10_000 });
  await page.getByRole("heading", { name: /You don't need the right words to begin/i }).waitFor({ state: "visible", timeout: 5_000 });
  await smoothScroll("#ai-with-boundaries");
  await page.getByRole("heading", { name: /AI can help with the words/i }).waitFor({ state: "visible", timeout: 3_000 });
  await holdUntil(167, "Meta Wonder, Spark, and Voice Transcribe roles with peer-support boundaries");
  await smoothScroll("#the-intent");
  await page.getByRole("heading", { name: /A gentler route from feeling stuck/i }).waitFor({ state: "visible", timeout: 3_000 });
  await holdUntil(177, "Impact close with honest, intended-outcome statement");

  if (errors.length) throw new Error(`Capture observed application errors: ${errors.join("; ")}`);
} catch (error) {
  captureFailure = error;
  console.error(`Capture stopped: ${error instanceof Error ? error.message : String(error)}`);
} finally {
  const video = page.video();
  await context.close();
  if (video) {
    const target = resolve(outDir, "harmonise-live-v2.webm");
    await video.saveAs(target);
    const manifest = {
      video: target,
      baseURL,
      targetRuntimeSeconds: 180,
      marks,
      expectedResponses,
      errors,
      modelAttributions,
      savedPrivateConversation,
      communityDataChanged: false,
      captureElapsedSeconds: elapsedSeconds(),
      failure: captureFailure instanceof Error ? captureFailure.message : captureFailure ? String(captureFailure) : null,
    };
    await writeFile(resolve(outDir, "capture-manifest-v2.json"), `${JSON.stringify(manifest, null, 2)}\n`);
    console.log(JSON.stringify(manifest, null, 2));
  }
  await browser.close();
}

if (captureFailure) throw captureFailure;
